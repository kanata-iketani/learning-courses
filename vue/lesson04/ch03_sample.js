// 四則演算は Python とほぼ同じです
console.log(10 + 3);  // 13
console.log(10 - 3);  // 7
console.log(10 * 3);  // 30
console.log(10 / 4);  // 2.5 (整数どうしでも小数になります)
console.log(10 % 3);  // 1 (割り算の余り)

// 注意: 文字列に + を使うと「連結」になります
console.log("10" + 5);  // 105 (数値の 15 ではありません)

// 変数を使った計算も同じです
const price = 120;
const count = 3;
console.log(price * count);  // 360
